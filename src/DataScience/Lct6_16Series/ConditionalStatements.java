package DataScience.Lct6_16Series;
import java.util.*;
public class ConditionalStatements {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int a = sc.nextInt();
        for (int i = 1; i < a; i++) {
            System.out.println(i);
        }
        System.out.println("Done");
    }
}
